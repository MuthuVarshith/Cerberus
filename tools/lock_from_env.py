"""Write autonomous-pr-fixer/requirements.lock from the installed environment.

Used because pip-compile / uv were not available offline. Walks the dependency closure of the
pyproject dependencies plus the given extras via importlib.metadata and pins the installed versions.
Dependencies reached only through environment markers keep their marker.

    python tools/lock_from_env.py retrieval langgraph dev
"""
from __future__ import annotations

import sys
import tomllib
from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1] / "autonomous-pr-fixer"


def main(extras: list[str]) -> int:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    roots = list(project["dependencies"])
    for extra in extras:
        roots += project["optional-dependencies"][extra]
    pins: dict[str, tuple[str, str, set[str]]] = {}
    queue = [(Requirement(r), set()) for r in roots]
    missing: list[str] = []
    while queue:
        req, wanted = queue.pop()
        marker = ""
        if req.marker:
            env_ok = [req.marker.evaluate({"extra": e}) for e in (wanted or {""})]
            if "extra" in str(req.marker):
                if not any(env_ok):
                    continue
            else:
                marker = str(req.marker)
                if not req.marker.evaluate({"extra": ""}):
                    continue
        name = canonicalize_name(req.name)
        try:
            dist = metadata.distribution(req.name)
        except metadata.PackageNotFoundError:
            missing.append(req.name)
            continue
        seen = pins.get(name)
        new_extras = set(req.extras) - (seen[2] if seen else set())
        if seen:
            old_marker = seen[1]
            pins[name] = (seen[0], "" if not old_marker or not marker else old_marker, seen[2] | set(req.extras))
            if not new_extras:
                continue
        else:
            pins[name] = (dist.version, marker, set(req.extras))
        for dep in dist.requires or []:
            queue.append((Requirement(dep), set(req.extras)))
    lines = [
        "# Exact versions for CI and reproducible installs. Generated by tools/lock_from_env.py",
        f"# (extras: {', '.join(extras) or 'none'}) from the dependency closure of pyproject.toml as installed",
        "# on the development machine (Windows 11, Python 3.13); pip-compile/uv were not available offline.",
        "# Not locked: the [swebench] extra. Linux-only transitive deps are resolved by pip at install time.",
    ]
    for name in sorted(pins):
        version, marker, _ = pins[name]
        lines.append(f"{name}=={version}" + (f" ; {marker}" if marker else ""))
    (ROOT / "requirements.lock").write_text("\n".join(lines) + "\n", encoding="utf-8")
    if missing:
        print("not installed:", sorted(set(missing)), file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
